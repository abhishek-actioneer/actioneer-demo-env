function makeTx(
  idx: number,
  playerId: string,
  playerName: string,
  skuId: string,
  skuName: string,
  amount: number,
  day: number,
  statusOverride?: "completed" | "pending" | "refunded" | "cancelled" | "failed"
): Transaction {
  const status = statusOverride ?? txStatuses[idx % txStatuses.length];
  const created = daysAgoISO(day);
  return {
    id: `tx-${String(idx + 1).padStart(4, "0")}`,
    playerId,
    playerName,
    skuId,
    skuName,
    amount,
    currency: "USD",
    status,
    paymentMethod: payMethods[idx % payMethods.length],
    createdAt: created,
    settledAt: status === "completed" ? daysAgo(Math.max(0, day - 1)) : undefined,
    refundedAt: status === "refunded" ? daysAgo(Math.max(0, day - 2)) : undefined,
    gatewayRef: `gw_${Math.random().toString(36).slice(2, 14)}`,
    ipAddress: `${72 + (idx % 30)}.${100 + (idx % 55)}.${idx % 256}.${(idx * 7) % 256}`,
    deviceType: devices[idx % devices.length],
    settlementAmount: status === "completed" ? +(amount * 0.92).toFixed(2) : undefined,
    fees: status === "completed" ? +(amount * 0.08).toFixed(2) : undefined,
  };
}

