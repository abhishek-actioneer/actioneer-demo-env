// ── Helper: generate dates relative to "today" ──

/** Generate 14-day daily revenue array. Distributes total revenue with realistic noise. */
function dailyRevenue(total: number, trend: "up" | "down" | "flat" | "spike" = "flat"): number[] {
  if (total === 0) return Array(14).fill(0);
  const days = 14;
  const base = total / days;
  return Array.from({ length: days }, (_, i) => {
    const noise = 0.5 + Math.random();
    let multiplier = noise;
    if (trend === "up") multiplier = noise * (0.5 + (i / days) * 1.2);
    else if (trend === "down") multiplier = noise * (1.2 - (i / days) * 0.8);
    else if (trend === "spike") multiplier = i >= 9 && i <= 11 ? noise * 2.5 : noise * 0.6;
    return Math.round(base * multiplier * 100) / 100;
  });
}

function daysAgo(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d.toISOString().split("T")[0];
}

function daysAgoISO(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() - n);
  d.setHours(
    Math.floor(Math.random() * 14) + 8,
    Math.floor(Math.random() * 60),
    Math.floor(Math.random() * 60)
  );
  return d.toISOString();
}

