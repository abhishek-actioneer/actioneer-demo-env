/* ─────────────────────────────────────────────
   Shared types + data for connector dataset tables
   ───────────────────────────────────────────── */

export type TableType   = "cube" | "view";
export type ColType     = "string" | "number" | "time";
export type MemberType  = "dimension" | "measure";
export type TableStatus = "clean" | "syncing" | "warning";

export interface ColumnDef {
  name: string;
  type: ColType;
  member: MemberType;
  description: string;
  isPrimaryKey?: boolean;
}

export interface TableDef {
  id: string;
  name: string;
  description: string;
  type: TableType;
  columnCount: number;
  rowCount: string;
  status: TableStatus;
  columns: ColumnDef[];
}

export interface DatasetDetail {
  connectorName: string;
  datasetName: string;
  version: string;
  createdAt?: string;
  tables: TableDef[];
}

export function getDataTypeBadge(col: ColumnDef): { label: string; bg: string; color: string } {
  if (col.type === "time")
    return { label: "Time",   bg: "var(--badge-amber-bg)",  color: "var(--badge-amber-text)"  };
  if (col.type === "number" && col.member === "measure")
    return { label: "Sum",    bg: "var(--badge-blue-bg)",   color: "var(--badge-blue-text)"   };
  if (col.type === "number")
    return { label: "Float",  bg: "var(--badge-red-bg)",    color: "var(--badge-red-text)"    };
  return   { label: "String", bg: "var(--badge-purple-bg)", color: "var(--badge-purple-text)" };
}

