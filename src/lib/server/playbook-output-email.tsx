export interface RenderPlaybookEmailInput {
  playbook: PlaybookV2;
  run: PlaybookRunHistory;
  subject: string;
}

export async function renderPlaybookOutputEmail(input: RenderPlaybookEmailInput): Promise<{
  html: string;
  markdown: string;
  bodyHtml: string;
}> {
  const markdown = buildPlaybookOutputMarkdown(input.playbook, input.run);
  const bodyHtml = markdownToEmailHtml(markdown);

  const html = await render(
    <FixedPlaybookEmail
      preheader={input.playbook.description}
      headline={input.subject}
      subhead={input.playbook.name}
      bodyHtml={bodyHtml}
    />,
    { pretty: false },
  );
  return { html, markdown, bodyHtml };
}

